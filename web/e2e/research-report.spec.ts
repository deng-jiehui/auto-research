import { test, expect } from "@playwright/test";
import { readFile } from "node:fs/promises";

test("独立调研生成证据矩阵和报告，可查看引用、导出并刷新恢复", async ({ page, request }, testInfo) => {
  const reportReads: string[] = [];
  page.on("request", (req) => { if (req.method() === "GET" && /\/api\/projects\/[^/]+\/reports\/[^/]+$/.test(req.url())) reportReads.push(req.url()); });
  await request.put("/api/runtime/model", { data: { mode: "fixture", endpoint: "", model: "", api_key: "" } });
  const project = await (await request.post("/api/projects", { data: { title: "报告验收" } })).json();
  const created = await (await request.post(`/api/projects/${project.id}/research`, { data: { question: "比较可复现的预测基线", idempotency_key: "report-start" } })).json();
  await page.goto(`/p/${project.id}/research/${created.run.id}`);
  await page.getByRole("button", { name: "确认计划并继续", exact: true }).click();
  await page.getByRole("button", { name: "确认纳入并继续", exact: true }).click();
  const panel = page.getByRole("region", { name: "证据矩阵与研究报告" });
  await expect(panel.getByRole("heading", { name: "研究报告", exact: true })).toBeVisible();
  await expect(panel.getByRole("table", { name: "当前纳入论文的五字段证据矩阵" })).toContainText("方法");
  await expect(panel.getByRole("table", { name: "当前纳入论文的五字段证据矩阵" })).toContainText("复现条件");
  await expect(panel.getByRole("combobox", { name: "报告版本" })).toHaveValue(/.+/);
  await expect(panel.getByRole("heading", { name: "方法比较", exact: true })).toBeVisible();
  await expect(panel).toContainText("离线");
  await page.waitForRequest((req) => req.method() === "GET" && req.url().endsWith(`/research/${created.run.id}/snapshot`));
  expect(reportReads).toHaveLength(1);
  const report = await (await request.get(`/api/projects/${project.id}/reports/${(await (await request.get(`/api/projects/${project.id}/research/${created.run.id}`)).json()).latest_report.id}`)).json();
  expect(report.matrix_hash).toBe(report.matrix.hash);
  expect(report.references.length).toBeGreaterThan(0);
  const other = await (await request.post("/api/projects", { data: { title: "隔离项目" } })).json();
  expect((await request.get(`/api/projects/${other.id}/reports/${report.id}`)).status()).toBe(404);
  const downloadEvent = page.waitForEvent("download");
  await panel.getByRole("button", { name: "导出 Markdown", exact: true }).click();
  const download = await downloadEvent;
  expect(await readFile((await download.path())!, "utf8")).toBe(report.markdown);
  await page.reload();
  await expect(panel.getByRole("heading", { name: "方法比较", exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("research-report.png"), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth)).toBeLessThanOrEqual(2);
  await expect(panel.getByRole("button", { name: "导出 Markdown", exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("research-report-mobile.png"), fullPage: true });
  await page.setViewportSize({ width: 1440, height: 960 });
  await panel.getByRole("link", { name: "查看原文", exact: true }).first().click();
  await expect(page).toHaveURL(/papers\?paper=.+&evidence=.+/);
  await expect(page.getByText(report.references[0].quote, { exact: true }).first()).toBeVisible();
});

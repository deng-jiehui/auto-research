import { test, expect } from "@playwright/test";

test("会话委派独立研究，任务页审核，来源会话仅同步结果和查询入口", async ({ page, request }, testInfo) => {
  await request.put("/api/runtime/model", { data: { mode: "fixture", endpoint: "", model: "", api_key: "" } });
  const project = await (await request.post("/api/projects", { data: { title: "独立研究验收" } })).json();
  const session = await (await request.post(`/api/projects/${project.id}/sessions`, { data: { title: "日常讨论" } })).json();
  const chatURL = `/p/${project.id}/s/${session.id}`;
  const fullResearchReads: string[] = [];
  page.on("request", (req) => { if (req.method() === "GET" && req.url().endsWith(`/api/projects/${project.id}/research`)) fullResearchReads.push(req.url()); });
  await page.goto(chatURL);
  await page.getByRole("textbox", { name: "消息", exact: true }).fill("开始调研可复现的预测基线");
  await page.getByRole("button", { name: "发送消息", exact: true }).click();
  const cards = page.getByRole("region", { name: "独立调研任务" });
  await expect(cards.getByRole("link", { name: "打开调研任务", exact: true })).toBeVisible();
  await expect(page.getByRole("region", { name: "研究计划审核" })).toHaveCount(0);
  await expect(page.getByRole("textbox", { name: "消息", exact: true })).toBeEnabled();
  expect(fullResearchReads).toHaveLength(0);
  await page.getByRole("textbox", { name: "消息", exact: true }).fill("你好，先继续讨论");
  await page.getByRole("button", { name: "发送消息", exact: true }).click();
  await expect(page.getByText("你好，先继续讨论", { exact: true })).toBeVisible();
  await cards.getByRole("link", { name: "打开调研任务", exact: true }).click();
  await expect(page).toHaveURL(/\/research\/[^/]+$/);
  await expect(page.getByRole("textbox", { name: "消息", exact: true })).toHaveCount(0);
  await page.getByRole("button", { name: "确认计划并继续", exact: true }).click();
  await page.getByRole("button", { name: "确认纳入并继续", exact: true }).click();
  const status = page.locator(".research-task-status");
  await expect(status).toHaveAttribute("data-state", "completed");
  await expect(status).toHaveText("已完成");
  await expect(page.locator(".papers-header").getByText("completed", { exact: true })).toHaveCount(0);
  await expect(page.locator(".papers-header").getByText("已结束", { exact: true })).toHaveCount(0);
  for (const viewport of [{ width: 1440, height: 960 }, { width: 390, height: 844 }]) {
    await page.setViewportSize(viewport);
    const badge = await status.boundingBox();
    const retry = await page.getByRole("button", { name: "重新调研", exact: true }).boundingBox();
    expect(badge).not.toBeNull();
    expect(retry).not.toBeNull();
    expect(badge!.height).toBeLessThan(retry!.height);
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth)).toBeLessThanOrEqual(2);
    await page.locator(".papers-header").screenshot({ path: testInfo.outputPath(`task-status-${viewport.width}.png`), animations: "disabled" });
  }
  await page.setViewportSize({ width: 1440, height: 960 });
  const runID = page.url().split("/research/")[1];
  const runs = await (await request.get(`/api/projects/${project.id}/research`)).json();
  expect(runs.items).toHaveLength(1);
  expect(runs.items[0].origin_session_id).toBe(session.id);
  expect(runs.items[0].session_id).not.toBe(session.id);
  const sessions = await (await request.get(`/api/projects/${project.id}/sessions`)).json();
  expect(sessions.items.map((item: { id: string }) => item.id)).toEqual([session.id]);
  await page.goto(chatURL);
  await expect(cards.locator("article")).toHaveCount(1);
  await expect(cards).toContainText("完成 1 篇");
  await expect(cards).toContainText(`research://runs/${runID}.json`);
  await expect(page.getByRole("region", { name: "逐篇论文分析" })).toHaveCount(0);
  await page.reload();
  await expect(cards).toContainText("完成 1 篇");
  await page.screenshot({ path: testInfo.outputPath("chat-research-result.png"), fullPage: true });
  await cards.getByRole("link", { name: "打开调研任务", exact: true }).click();
  await page.getByRole("button", { name: "重新调研", exact: true }).click();
  await expect(page).not.toHaveURL(new RegExp(`/research/${runID}$`));
  await expect(page.getByRole("region", { name: "研究计划审核" })).toBeVisible();
  const after = await (await request.get(`/api/projects/${project.id}/research`)).json();
  expect(after.items).toHaveLength(2);
  expect(after.items.find((item: { id: string }) => item.id === runID).phase).toBe("reported");
  expect(after.items[0].previous_run_id).toBe(runID);
  await page.screenshot({ path: testInfo.outputPath("independent-task-plan.png"), fullPage: true });
  const cancelledID = after.items[0].id;
  await page.getByRole("button", { name: "结束任务", exact: true }).click();
  await expect(status).toHaveAttribute("data-state", "cancelled");
  await expect(status).toHaveText("已取消");
  await page.getByRole("button", { name: "重新调研", exact: true }).click();
  await expect(page.getByRole("region", { name: "研究计划审核" })).toBeVisible();
  const restarted = await (await request.get(`/api/projects/${project.id}/research`)).json();
  expect(restarted.items[0].previous_run_id).toBe(cancelledID);
  expect(restarted.items.find((item: { id: string }) => item.id === cancelledID).execution_state).toBe("cancelled");
});

test("任务详情确认删除，移除成果和来源会话卡片，保留论文资料", async ({ page, request }, testInfo) => {
  await request.put("/api/runtime/model", { data: { mode: "fixture", endpoint: "", model: "", api_key: "" } });
  const project = await (await request.post("/api/projects", { data: { title: "删除已完成调研" } })).json();
  const session = await (await request.post(`/api/projects/${project.id}/sessions`, { data: { title: "来源会话" } })).json();
  const { run } = await (await request.post(`/api/projects/${project.id}/research`, { data: { question: "研究可复现的预测基线", origin_session_id: session.id, idempotency_key: crypto.randomUUID() } })).json();
  const taskPath = `/api/projects/${project.id}/research/${run.id}`;
  await page.goto(`/p/${project.id}/research/${run.id}`);
  await page.getByRole("button", { name: "确认计划并继续", exact: true }).click();
  await page.getByRole("button", { name: "确认纳入并继续", exact: true }).click();
  await expect(page.locator(".research-task-status")).toHaveAttribute("data-state", "completed");
  const completed = await (await request.get(taskPath)).json();
  expect(completed.latest_report.id).toBeTruthy();
  const paperID = completed.work_items[0].paper_id;

  await page.getByRole("button", { name: "删除任务", exact: true }).click();
  const dialog = page.getByRole("dialog", { name: "删除调研任务", exact: true });
  await expect(dialog).toBeVisible();
  await expect(dialog.getByRole("textbox")).toHaveCount(0);
  await expect(dialog).toContainText("论文库");
  await dialog.getByRole("button", { name: "取消", exact: true }).click();
  expect((await request.get(taskPath)).status()).toBe(200);

  await page.getByRole("button", { name: "删除任务", exact: true }).click();
  await dialog.screenshot({ path: testInfo.outputPath("delete-research-confirmation.png") });
  await dialog.getByRole("button", { name: "确认永久删除", exact: true }).click();
  await expect(page).toHaveURL(new RegExp(`/p/${project.id}/research$`));
  await expect(page.getByRole("status")).toContainText("调研任务已删除");
  expect((await request.get(taskPath)).status()).toBe(404);
  expect((await request.get(`/api/projects/${project.id}/reports/${completed.latest_report.id}`)).status()).toBe(404);
  expect((await request.get(`/api/projects/${project.id}/papers/${paperID}`)).status()).toBe(200);
  expect((await request.get(`/api/projects/${project.id}/sessions/${run.session_id}`)).status()).toBe(404);
  expect((await request.get(`/api/projects/${project.id}/sessions/${session.id}`)).status()).toBe(200);
  await page.reload();
  await expect(page.locator(".research-run-list article")).toHaveCount(0);
  await page.goto(`/p/${project.id}/s/${session.id}`);
  await expect(page.getByRole("region", { name: "独立调研任务" })).toHaveCount(0);
});

test("任务列表可删除已取消调研，活动任务提示先结束", async ({ page, request }) => {
  await request.put("/api/runtime/model", { data: { mode: "fixture", endpoint: "", model: "", api_key: "" } });
  const project = await (await request.post("/api/projects", { data: { title: "列表删除调研" } })).json();
  const { run } = await (await request.post(`/api/projects/${project.id}/research`, { data: { question: "待结束的调研", idempotency_key: crypto.randomUUID() } })).json();
  const taskPath = `/api/projects/${project.id}/research/${run.id}`;
  await expect.poll(async () => (await (await request.get(taskPath)).json()).execution_state).toBe("awaiting_input");
  await page.goto(`/p/${project.id}/research`);
  const card = page.locator(".research-run-list article.card").filter({ has: page.getByRole("heading", { name: "待结束的调研", exact: true }) });
  await expect(card.getByRole("button", { name: "删除任务", exact: true })).toBeDisabled();
  await expect(card).toContainText("结束任务后可删除");
  expect((await request.delete(taskPath)).status()).toBe(409);
  await card.getByRole("link", { name: "打开调研任务", exact: true }).click();
  await page.getByRole("button", { name: "结束任务", exact: true }).click();
  await expect(page.locator(".research-task-status")).toHaveAttribute("data-state", "cancelled");
  await page.goto(`/p/${project.id}/research`);
  await card.getByRole("button", { name: "删除任务", exact: true }).click();
  await page.getByRole("dialog", { name: "删除调研任务", exact: true }).getByRole("button", { name: "确认永久删除", exact: true }).click();
  await expect(page.locator(".research-run-list article")).toHaveCount(0);
  await page.reload();
  await expect(page.locator(".research-run-list article")).toHaveCount(0);
  expect((await request.get(taskPath)).status()).toBe(404);
});
